export type Severity = "critical" | "high" | "medium" | "low";

export interface GuardFinding {
  ruleId: string;
  ruleName: string;
  severity: Severity;
  line: number;
  start: number;
  end: number;
  preview: string;
  why: string;
  mintCommand: string;
}

export interface GuardResult {
  findings: GuardFinding[];
  scannedLines: number;
  elapsedMs: number;
}

