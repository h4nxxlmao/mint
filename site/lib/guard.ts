const PLACEHOLDER_PATTERNS = [
  /^<.*>$/,
  /^\$\{.*\}$/,
  /^\{\{.*\}\}$/,
  /^x{4,}$/i,
  /^\.{3,}$/,
  /^[-_=]{4,}$/,
  /^(?:process\.env|os\.environ|env|import\.meta\.env)/,
  /\b(?:process|import)\.env\b/,
  /^(?:your|my|insert|put|add|replace|change|set)[-_ ][A-Za-z0-9_-]*$/i,
  /^(?:string|number|boolean|unknown|any|null|undefined)$/,
];

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const DIGEST = /^(?:[0-9a-f]{32}|[0-9a-f]{40}|[0-9a-f]{64}|[0-9a-f]{128})$/i;
const HEX_LIKE = /^[0-9a-f]+$/i;
const URL = /^[a-z][a-z0-9+.-]*:\/\//i;
const CODE_LIKE = /[(){}[\];<>`]|=>|\$\{|\$\(|\s/;
const SINGLE_CASE = /^[a-z]+$|^[A-Z]+$|^[0-9]+$/;

function shannonEntropy(text: string): number {
  if (text.length === 0) return 0;
  const counts = new Map<string, number>();
  for (const char of text) counts.set(char, (counts.get(char) ?? 0) + 1);
  let value = 0;
  for (const count of counts.values()) {
    const probability = count / text.length;
    value -= probability * Math.log2(probability);
  }
  return value;
}

function hasSequentialRun(text: string, minRun = 5): boolean {
  let ascending = 1;
  let descending = 1;
  for (let index = 1; index < text.length; index += 1) {
    const delta = text.charCodeAt(index) - text.charCodeAt(index - 1);
    ascending = delta === 1 ? ascending + 1 : 1;
    descending = delta === -1 ? descending + 1 : 1;
    if (ascending >= minRun || descending >= minRun) return true;
  }
  return false;
}

function isPlaceholder(text: string): boolean {
  const lower = text.toLowerCase();
  return (
    PLACEHOLDER_WORDS.some((word) => lower.includes(word)) ||
    PLACEHOLDER_PATTERNS.some((pattern) => pattern.test(text))
  );
}

function acceptableValue(value: string): boolean {
  const text = value.trim();
  if (text.length < 4) return false;
  if (/^(?:true|false|null|none|nil|undefined|\d+)$/i.test(text)) return false;
  if (hasSequentialRun(text)) return false;
  if (UUID.test(text)) return false;
  if (isPlaceholder(text)) return false;
  return true;
}

function previewSecret(value: string): string {
  const text = value.trim();
  if (text.length < 12) return "***";
  return `${text.slice(0, 4)}...${text.slice(-2)}`;
}

function shouldScanEntropy(value: string, line: string): boolean {
  if (value.length < 20 || value.length > 200) return false;
  if (isPlaceholder(value)) return false;
  if (/^data:image\/|^iVBORw0KGgo|^\/9j\/|^R0lGOD/i.test(value)) return false;
  if (URL.test(value)) return false;
  if (UUID.test(value)) return false;
  if (CODE_LIKE.test(value)) return false;
  if (hasSequentialRun(value)) return false;
  if (DIGEST.test(value) && !/(?:key|token|secret|api|auth|pass)/i.test(line)) return false;
  if (HEX_LIKE.test(value) && !/(?:key|token|secret|api|auth|pass)/i.test(line)) return false;
  if (/^[A-Za-z]+(?:[ ._-][A-Za-z]+){2,}$/.test(value)) return false;
  const required = SINGLE_CASE.test(value) ? 5.3 : 4.5;
  return shannonEntropy(value) >= required;
}

function extractCandidates(line: string): Array<{ value: string; index: number }> {
  const seen = new Set<number>();
  const candidates: Array<{ value: string; index: number }> = [];
  for (const pattern of [/"([^"\\\n]{8,200})"/g, /'([^'\\\n]{8,200})'/g, /`([^`\\\n]{8,200})`/g]) {
    pattern.lastIndex = 0;
    for (;;) {
      const match = pattern.exec(line);
      if (match === null) break;
      const value = match[1];
      const index = match.index + match[0].indexOf(value);
      if (!seen.has(index)) {
        seen.add(index);
        candidates.push({ value, index });
      }
      if (match.index === pattern.lastIndex) pattern.lastIndex += 1;
    }
  }
  const assignment = /[:=]\s*([A-Za-z0-9+/_\-.]{8,200})/g;
  for (;;) {
    const match = assignment.exec(line);
    if (match === null) break;
    const value = match[1];
    const index = match.index + match[0].indexOf(value);
    if (!seen.has(index)) {
      seen.add(index);
      candidates.push({ value, index });
    }
    if (match.index === assignment.lastIndex) assignment.lastIndex += 1;
  }
  return candidates;
}

function findingKey(line: number, value: string): string {
  return `${line}|${value}`;
}

function scanLine(line: string, lineNumber: number, findings: GuardFinding[], seen: Set<string>): void {
  if (line.trim() === "" || line.length > MAX_LINE) return;
  if (/mintguard:\s*ignore\b/i.test(line)) return;

  const lower = line.toLowerCase();
  const usedValues = new Set<string>();

  for (const rule of RULES) {
    if (!rule.keywords.some((keyword) => lower.includes(keyword))) continue;
    const flags = [...new Set([...(rule.flags ?? ""), "g", "d"])].join("");
    const regex = new RegExp(rule.regex, flags);
    let match: RegExpExecArray | null;
    let matches = 0;
    while ((match = regex.exec(line)) !== null) {
      if (match.index === regex.lastIndex) regex.lastIndex += 1;
      matches += 1;
      if (matches > MAX_MATCHES) break;
      const capture = rule.capture ?? 0;
      const indices = match.indices?.[capture];
      const raw = match[capture] ?? "";
      const value = raw.trim();
      if (!indices || !acceptableValue(value)) continue;
      const start = indices[0] + (raw.length - raw.trimStart().length);
      const end = indices[1] - (raw.length - raw.trimEnd().length);
      usedValues.add(value);
      const key = findingKey(lineNumber, value);
      if (seen.has(key)) continue;
      seen.add(key);
      findings.push({
        ruleId: rule.id,
        ruleName: rule.name,
        severity: rule.severity,
        line: lineNumber,
        start,
        end,
        preview: previewSecret(value),
        why: rule.why,
        mintCommand: rule.mintCommand,
      });
    }
  }

  let considered = 0;
  for (const candidate of extractCandidates(line)) {
    if (considered >= 12) break;
    considered += 1;
    if (usedValues.has(candidate.value)) continue;
    if (!acceptableValue(candidate.value)) continue;
    if (!shouldScanEntropy(candidate.value, line)) continue;
    usedValues.add(candidate.value);
    const key = findingKey(lineNumber, candidate.value);
    if (seen.has(key)) continue;
    seen.add(key);
    findings.push({
      ruleId: ENTROPY_RULE.id,
      ruleName: ENTROPY_RULE.name,
      severity: ENTROPY_RULE.severity,
      line: lineNumber,
      start: candidate.index,
      end: candidate.index + candidate.value.length,
      preview: previewSecret(candidate.value),
      why: ENTROPY_RULE.why,
      mintCommand: ENTROPY_RULE.mintCommand,
    });
  }
}

export function scanText(text: string): GuardResult {
  const started = performance.now();
  const lines = text.split(/\r?\n/);
  const findings: GuardFinding[] = [];
  const seen = new Set<string>();

  for (let index = 0; index < lines.length; index += 1) {
    scanLine(lines[index], index + 1, findings, seen);
  }

  findings.sort(
    (left, right) =>
      SEVERITY_RANK[right.severity] - SEVERITY_RANK[left.severity] ||
      left.line - right.line ||
      left.start - right.start,
  );

  return {
    findings,
    scannedLines: lines.length,
    elapsedMs: Math.max(0, performance.now() - started),
  };
}

export interface RedactionSegment {
  text: string;
  redacted: boolean;
}

export function redactLine(line: string, findings: readonly GuardFinding[]): RedactionSegment[] {
  const spans = findings
    .filter((finding) => finding.start < finding.end)
    .sort((left, right) => left.start - right.start)
    .reduce<Array<{ start: number; end: number }>>((merged, finding) => {
      const previous = merged[merged.length - 1];
      if (previous && finding.start <= previous.end) {
        previous.end = Math.max(previous.end, finding.end);
      } else {
        merged.push({ start: finding.start, end: finding.end });
      }
      return merged;
    }, []);

  if (spans.length === 0) return [{ text: line, redacted: false }];
  const segments: RedactionSegment[] = [];
  let cursor = 0;
  for (const span of spans) {
    if (span.start > cursor) segments.push({ text: line.slice(cursor, span.start), redacted: false });
    segments.push({ text: "••••••", redacted: true });
    cursor = span.end;
  }
  if (cursor < line.length) segments.push({ text: line.slice(cursor), redacted: false });
  return segments;
}

